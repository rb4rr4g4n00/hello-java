public class VariablesAndConstants {

    public static void main(String[] args) {
        // Variables
        // TIPO NOMBRE = VALOR;
        String ejemploString = "Carlos Barragan";
        System.out.println(ejemploString);
        ejemploString = "Aura Garcia";
        System.out.println(ejemploString);


        // Constantes
        // 1. Inician con la palabra final
        // 2. El nombre se escribe en MAYUS_SNAKE_CASE
        final String EJEMPLO_CONSTANTE_STRING = "Ismael Barragan";
        System.out.println(EJEMPLO_CONSTANTE_STRING);
    }
}
